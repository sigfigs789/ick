#!/usr/bin/env node
/**
 * Renders the same tones as the web app's src/audio/sound.ts (Web Audio
 * oscillator + exponential gain envelope) to short 16-bit PCM WAV files,
 * then emits them as base64 data URIs in src/audio/tones.ts so expo-audio
 * can play them with no bundled asset files -- same "nothing to load"
 * philosophy as the web version, just precomputed instead of synthesized
 * live (React Native has no Web Audio API to synthesize with at runtime).
 *
 * Run: node scripts/synth-tones.js
 */
const fs = require("fs");
const path = require("path");

const SAMPLE_RATE = 44100;

function expRamp(v0, v1, t, t0, t1) {
  if (t <= t0) return v0;
  if (t >= t1) return v1;
  const frac = (t - t0) / (t1 - t0);
  return v0 * Math.pow(v1 / v0, frac);
}

/** One oscillator note with the same attack/decay envelope shape as tone() in sound.ts. */
function renderTone(buf, freq, startTime, duration, opts = {}) {
  const type = opts.type ?? "sine";
  const peak = opts.peakGain ?? 0.15;
  const glideTo = opts.glideTo;
  const gainStart = startTime;
  const attackEnd = startTime + 0.012;
  const gainEnd = startTime + duration;
  const stopTime = startTime + duration + 0.03;

  const startSample = Math.floor(startTime * SAMPLE_RATE);
  const stopSample = Math.min(buf.length, Math.ceil(stopTime * SAMPLE_RATE));

  let phase = 0;
  for (let i = startSample; i < stopSample; i++) {
    const t = i / SAMPLE_RATE;
    const f = glideTo ? expRamp(freq, glideTo, t, startTime, gainEnd) : freq;
    phase += (2 * Math.PI * f) / SAMPLE_RATE;

    let wave;
    if (type === "sine") {
      wave = Math.sin(phase);
    } else if (type === "square") {
      wave = Math.sin(phase) >= 0 ? 1 : -1;
    } else if (type === "triangle") {
      const p = (phase / (2 * Math.PI)) % 1;
      wave = 4 * Math.abs(p - 0.5) - 1;
    } else {
      wave = Math.sin(phase);
    }

    let gain;
    if (t < attackEnd) {
      gain = expRamp(0.0001, peak, t, gainStart, attackEnd);
    } else {
      gain = expRamp(peak, 0.0001, t, attackEnd, gainEnd);
    }

    buf[i] += wave * gain;
  }
}

function makeBuffer(totalDuration) {
  return new Float32Array(Math.ceil(totalDuration * SAMPLE_RATE));
}

function floatTo16BitPCM(float32) {
  const out = new Int16Array(float32.length);
  for (let i = 0; i < float32.length; i++) {
    const s = Math.max(-1, Math.min(1, float32[i]));
    out[i] = s < 0 ? s * 0x8000 : s * 0x7fff;
  }
  return out;
}

function encodeWav(float32) {
  const pcm = floatTo16BitPCM(float32);
  const blockAlign = 2; // mono, 16-bit
  const byteRate = SAMPLE_RATE * blockAlign;
  const dataSize = pcm.length * 2;
  const buf = Buffer.alloc(44 + dataSize);

  buf.write("RIFF", 0);
  buf.writeUInt32LE(36 + dataSize, 4);
  buf.write("WAVE", 8);
  buf.write("fmt ", 12);
  buf.writeUInt32LE(16, 16); // fmt chunk size
  buf.writeUInt16LE(1, 20); // PCM
  buf.writeUInt16LE(1, 22); // mono
  buf.writeUInt32LE(SAMPLE_RATE, 24);
  buf.writeUInt32LE(byteRate, 28);
  buf.writeUInt16LE(blockAlign, 30);
  buf.writeUInt16LE(16, 32); // bits per sample
  buf.write("data", 36);
  buf.writeUInt32LE(dataSize, 40);
  for (let i = 0; i < pcm.length; i++) {
    buf.writeInt16LE(pcm[i], 44 + i * 2);
  }
  return buf;
}

function toDataUri(wavBuffer) {
  return `data:audio/wav;base64,${wavBuffer.toString("base64")}`;
}

// --- Same note choices as sound.ts ---

const RARITY_RANK = {
  "Very Common": 0,
  Common: 1,
  Uncommon: 2,
  Rare: 3,
  "Extremely Rare": 4,
};

function renderAccept(rank) {
  const buf = makeBuffer(0.4);
  const base = 520 + rank * 55;
  renderTone(buf, base, 0, 0.11, { peakGain: 0.16 });
  renderTone(buf, base * 1.5, 0.09, 0.16, { peakGain: 0.14 });
  if (rank >= 3) {
    renderTone(buf, base * 2, 0.17, 0.16, { type: "triangle", peakGain: 0.1 });
  }
  return buf;
}

function renderReject() {
  const buf = makeBuffer(0.25);
  renderTone(buf, 180, 0, 0.16, { type: "square", peakGain: 0.07, glideTo: 110 });
  return buf;
}

function renderComplete() {
  const buf = makeBuffer(0.65);
  const notes = [523.25, 659.25, 783.99, 1046.5]; // C5 E5 G5 C6
  notes.forEach((freq, i) => renderTone(buf, freq, i * 0.1, 0.24, { peakGain: 0.15 }));
  return buf;
}

const entries = {};
for (const [rarity, rank] of Object.entries(RARITY_RANK)) {
  entries[rarity] = toDataUri(encodeWav(renderAccept(rank)));
}
const reject = toDataUri(encodeWav(renderReject()));
const complete = toDataUri(encodeWav(renderComplete()));

const out = `// AUTO-GENERATED by scripts/synth-tones.js -- do not edit by hand.
// Regenerate with: node scripts/synth-tones.js
import type { Rarity } from "../game/types";

export const ACCEPT_TONES: Record<Rarity, string> = {
  "Very Common": ${JSON.stringify(entries["Very Common"])},
  "Common": ${JSON.stringify(entries["Common"])},
  "Uncommon": ${JSON.stringify(entries["Uncommon"])},
  "Rare": ${JSON.stringify(entries["Rare"])},
  "Extremely Rare": ${JSON.stringify(entries["Extremely Rare"])},
};

export const REJECT_TONE = ${JSON.stringify(reject)};
export const COMPLETE_TONE = ${JSON.stringify(complete)};
`;

const outPath = path.join(__dirname, "..", "src", "audio", "tones.ts");
fs.writeFileSync(outPath, out);
console.log(`Wrote ${outPath} (${(out.length / 1024).toFixed(1)} KB)`);
